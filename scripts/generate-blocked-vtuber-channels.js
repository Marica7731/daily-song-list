#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");
const {
  DEFAULT_BLOCKLIST_PATH,
  DEFAULT_GENERATED_ASSET_PATH,
  blocklistHash,
  canonicalizeBlocklist,
  loadBlocklist,
  stableJson,
  validateBlocklist,
} = require("./blocked-vtuber-utils");

const ROOT_DIR = path.resolve(__dirname, "..");

function main() {
  const sourcePath = path.resolve(ROOT_DIR, parseArg("--source") || DEFAULT_BLOCKLIST_PATH);
  const outPath = path.resolve(ROOT_DIR, parseArg("--out") || DEFAULT_GENERATED_ASSET_PATH);
  const blocklist = loadBlocklist(sourcePath);
  const validation = validateBlocklist(blocklist);
  if (!validation.ok) fail(validation.errors.join("\n"));
  const canonical = canonicalizeBlocklist(blocklist);
  const hash = blocklistHash(blocklist);
  const body = `// Generated by scripts/generate-blocked-vtuber-channels.js. Do not edit by hand.
(function initBlockedVtuberChannels(root, factory) {
  if (typeof module === "object" && module.exports) {
    module.exports = factory();
    return;
  }
  root.BlockedVtuberChannels = factory();
})(typeof globalThis !== "undefined" ? globalThis : window, function createBlockedVtuberChannels() {
  return {
    schemaVersion: ${JSON.stringify(canonical.schemaVersion)},
    listVersion: ${JSON.stringify(canonical.listVersion)},
    updatedAt: ${JSON.stringify(canonical.updatedAt)},
    blocklistHash: "${hash}",
    entries: ${stableJson(canonical.entries)}
  };
});
`;
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, body, "utf8");
  console.log(`BLOCKLIST_GENERATE_OK entries=${canonical.entries.length} hash=${hash} out=${path.relative(ROOT_DIR, outPath)}`);
}

function parseArg(name) {
  const index = process.argv.indexOf(name);
  if (index === -1) return "";
  return process.argv[index + 1] || "";
}

function fail(message) {
  console.error(`BLOCKLIST_GENERATE_FAIL ${message}`);
  process.exit(1);
}

if (require.main === module) main();
